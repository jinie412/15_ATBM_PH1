ALTER SESSION SET CONTAINER = QLDULIEUNOIBO;

CREATE TABLE DONVI (
    MADV   VARCHAR2(10) PRIMARY KEY,
    TENDV  VARCHAR2(70),
    LOAIDV VARCHAR2(5 CHAR) CHECK (LOAIDV IN (N'Khoa', N'Phòng')),
    TRGDV  VARCHAR2(8)
);

CREATE TABLE NHANVIEN (
    MANLD   VARCHAR2(8) PRIMARY KEY,
    HOTEN   VARCHAR2(70),
    PHAI    VARCHAR2(3 CHAR) CHECK (PHAI IN ('Nam', N'Nữ')),
    NGSINH  DATE,
    LUONG   NUMBER(10, 2),
    PHUCAP  NUMBER(10, 2),
    DT      VARCHAR2(10),
    VAITRO  VARCHAR2(10 CHAR) CHECK (VAITRO IN (
        'NVCB', 'GV', N'NV PĐT', 'NV PKT', 'NV TCHC', 'NV CTSV', N'TRGĐV'
    )),
    MADV    VARCHAR2(10),
    CONSTRAINT FK_NV_DV FOREIGN KEY (MADV) REFERENCES DONVI(MADV)
);

ALTER TABLE DONVI
ADD CONSTRAINT FK_DONVI_TRGDV FOREIGN KEY (TRGDV)
REFERENCES NHANVIEN(MANLD);

CREATE TABLE SINHVIEN (
    MASV     VARCHAR2(10) PRIMARY KEY,
    HOTEN    VARCHAR2(70),
    PHAI    VARCHAR2(3 CHAR) CHECK (PHAI IN ('Nam', N'Nữ')),
    NGSINH   DATE,
    DCHI     VARCHAR2(100),
    DT       VARCHAR2(10),
    KHOA     VARCHAR2(10),
    TINHTRANG VARCHAR2(20),
    CONSTRAINT FK_SV_KHOA FOREIGN KEY (KHOA) REFERENCES DONVI(MADV)
);

CREATE TABLE HOCPHAN (
    MAHP   VARCHAR2(8) PRIMARY KEY,
    TENHP  VARCHAR2(100),
    SOTC   NUMBER(2),
    STLT   NUMBER(3),
    STTH   NUMBER(3),
    MADV   VARCHAR2(10),
    CONSTRAINT FK_HP_DV FOREIGN KEY (MADV) REFERENCES DONVI(MADV)
);

CREATE TABLE MOMON (
    MAMM   VARCHAR2(8) PRIMARY KEY,
    MAHP   VARCHAR2(8),
    MAGV   VARCHAR2(8),
    HK     NUMBER(1) CHECK (HK IN (1, 2, 3)),
    NAM    NUMBER(4),
    CONSTRAINT FK_MM_HP FOREIGN KEY (MAHP) REFERENCES HOCPHAN(MAHP),
    CONSTRAINT FK_MM_GV FOREIGN KEY (MAGV) REFERENCES NHANVIEN(MANLD)
);

CREATE TABLE DANGKY (
    MASV    VARCHAR2(10),
    MAMM    VARCHAR2(8),
    DIEMTH  NUMBER(4, 2),
    DIEMQT  NUMBER(4, 2),
    DIEMCK  NUMBER(4, 2),
    DIEMTK  NUMBER(4, 2),
    PRIMARY KEY (MASV, MAMM),
    CONSTRAINT FK_DK_SV FOREIGN KEY (MASV) REFERENCES SINHVIEN(MASV),
    CONSTRAINT FK_DK_MM FOREIGN KEY (MAMM) REFERENCES MOMON(MAMM),
    CONSTRAINT CK_DIEMTH CHECK (DIEMTH BETWEEN 0 AND 10),
    CONSTRAINT CK_DIEMQT CHECK (DIEMQT BETWEEN 0 AND 10),
    CONSTRAINT CK_DIEMCK CHECK (DIEMCK BETWEEN 0 AND 10),
    CONSTRAINT CK_DIEMTK CHECK (DIEMTK BETWEEN 0 AND 10)
);

CREATE TABLE THONGBAO (
  ID NUMBER PRIMARY KEY,
  NOIDUNG VARCHAR2(4000),
  LABEL NUMBER
);




