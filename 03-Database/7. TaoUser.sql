-- Tạo user cho nhân viên phòng đào tạo
BEGIN
  FOR REC IN (SELECT MANLD FROM NHANVIEN WHERE VAITRO = 'NV PĐT') LOOP
    DECLARE
      v_username VARCHAR2(30) := REC.MANLD;
       
    BEGIN
      -- Tạo user và cấp quyền
      BEGIN
        EXECUTE IMMEDIATE 'CREATE USER ' || v_username || ' IDENTIFIED BY 123';
        EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO ' || v_username;
        EXECUTE IMMEDIATE 'GRANT NV_PDT TO ' || v_username;
        EXECUTE IMMEDIATE 'GRANT NVCB TO NV_PDT' ;
      EXCEPTION
        WHEN OTHERS THEN
          DBMS_OUTPUT.PUT_LINE('User ' || v_username || ' already exists or error occurred.');
      END;
    END;
  END LOOP;
END;
/

