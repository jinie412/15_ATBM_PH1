-- Cấp quyền thực thi hàm xác định role cho các user:
BEGIN
    FOR u IN (
        SELECT username 
        FROM dba_users 
        WHERE account_status = 'OPEN'
          AND oracle_maintained = 'N'
          AND (username LIKE 'NV%' OR username LIKE 'SV%')
    ) LOOP
        EXECUTE IMMEDIATE 'GRANT EXECUTE ON PDB_ADMIN.FUNC_XACDINH_DOITUONG TO ' || u.username;
         DBMS_OUTPUT.PUT_LINE('USER: ' || u.username);
    END LOOP;
END;
