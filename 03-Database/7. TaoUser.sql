-- Tạo user cho NVCB
BEGIN
  FOR emp IN (SELECT MANLD FROM NHANVIEN WHERE VAITRO = 'NVCB') LOOP
    BEGIN
      EXECUTE IMMEDIATE 'CREATE USER ' || emp.MANLD || ' IDENTIFIED BY 123';
      EXECUTE IMMEDIATE 'GRANT CONNECT TO ' || emp.MANLD;
      EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO ' || emp.MANLD;
      EXECUTE IMMEDIATE 'GRANT NVCB TO ' || emp.MANLD;
    END;
  END LOOP;
END;
