CREATE OR REPLACE PROCEDURE SP_XEMTHONGBAO(
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
    SELECT T.ID, T.NOIDUNG, L.LABEL
    FROM pdb_admin.THONGBAO T
    JOIN all_sa_labels L ON T.LABEL = L.LABEL_TAG;
END;
