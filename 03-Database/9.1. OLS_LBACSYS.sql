CREATE OR REPLACE PROCEDURE PROC_CREATE_LABEL (
    p_policy_name IN VARCHAR2,
    p_label_tag   IN VARCHAR2,
    p_label_value IN VARCHAR2,
    p_text        IN VARCHAR2  -- nội dung thông báo mới
)
AS
    v_new_id NUMBER;
BEGIN
    -- 1. Tạo nhãn OLS
    SA_LABEL_ADMIN.CREATE_LABEL(
        p_policy_name,
        p_label_tag,
        p_label_value
    );

     -- 2. Nếu p_text không rỗng thì thêm vào bảng THONGBAO
    IF TRIM(p_text) IS NOT NULL THEN
        -- Lấy ID mới
        SELECT NVL(MAX(ID), 0) + 1
        INTO v_new_id
        FROM pdb_admin.thongbao;

        -- Chèn thông báo mới
        INSERT INTO pdb_admin.thongbao(ID, NOIDUNG, LABEL)
        VALUES (
            v_new_id,
            p_text,
            TO_NUMBER(p_label_tag)  -- chuyển label_tag từ VARCHAR2 sang NUMBER
        );
    END IF;
END;
/


